def build_query_rewrite_messages(
    question: str,
    rewrite_count: int = 2,
) -> list[dict[str, str]]:
    """
    构造 Query Rewrite 使用的大模型消息。

    Query Rewrite 的作用：

        用户原始问题
            ↓
        生成多个语义一致、表达不同的检索 Query

    注意：
        这里只负责改写问题，
        不允许模型直接回答用户问题。
    """

    return [
        {
            "role": "system",
            "content": (
                "你是企业知识库 RAG 系统中的 Query Rewrite 模块。"

                "\n你的任务不是回答用户问题，"
                "而是把用户问题改写成多个适合知识库检索的查询。"

                "\n\n必须遵守以下规则："

                "\n1. 保持原始问题的核心语义不变。"

                "\n2. 可以、且应当用同义词、近义词或上位词替换"
                "问题中的关键词（如「优化器」可替换为"
                "「优化算法 / 优化方法 / 参数优化」），"
                "以提升检索召回；但不得编造原始问题中"
                "不存在的具体事实或答案（如不得直接写出"
                "某个具体优化器名称）。"

                "\n3. 不允许直接回答用户问题。"

                "\n4. 每一行只输出一个改写后的查询。"

                "\n5. 不要输出序号。"

                "\n6. 不要输出解释。"

                "\n7. 不要输出 Markdown。"

                "\n8. 不要重复生成完全相同的查询。"

                "\n9. 如果问题是在对比或区分两个及以上对象"
                "（如「A 和 B 的区别 / 差异 / 不同 / 相比」），"
                "必须为每个对象分别生成独立的检索查询"
                "（如「A 的主要内容和特点」"
                "「B 的主要内容和特点」），"
                "确保每个对象都能被单独检索到，"
                "不要生成仍把多个对象混在一起的查询。"
            ),
        },
        {
            "role": "user",
            "content": (
                f"原始问题：{question}\n"
                f"请生成 {rewrite_count} 个不同表达方式、"
                "且关键词有同义替换的检索查询。"
            ),
        },
    ]

def build_standalone_question_messages(
    history_text: str,
    question: str,
) -> list[dict[str, str]]:
    """
    构造「结合对话历史的追问改写」消息。

    多轮对话中，用户的追问常含指代 / 省略
    （如「有什么用」「它的原理呢」），需要结合
    历史改写成不依赖上下文也能理解的完整问题，
    再用于知识库检索。
    """

    return [
        {
            "role": "system",
            "content": (
                "你是多轮对话的问题改写助手。"
                "请根据对话历史，把用户最新问题改写成"
                "不依赖上下文也能完整理解的独立问题"
                "（补全省略的主语、对象和指代）。"
                "\n规则："
                "\n1. 只输出改写后的问题本身，"
                "不要任何解释、前缀、引号或 Markdown。"
                "\n2. 不得改变用户原意，"
                "不得添加对话中没有的新事实。"
                "\n3. 如果最新问题本身已经完整独立，"
                "原样返回，不要改动。"
                "\n4. 补全的主语 / 对象必须是对话历史中"
                "实际出现的具体技术实体或主题（例如 "
                "FastAPI、RAG、Hybrid Search、优化器、"
                "损失函数等），严禁使用「这份文档」「该"
                "文档」「文档内容」「这些内容」「本文」"
                "等笼统或元层面的指代，除非用户明确询问"
                "的就是文档本身。"
                "\n5. 当历史介绍了多个对象、而用户追问"
                "（如「有什么用」「原理呢」）未明确指向"
                "某一个时：若追问显然针对所有介绍过的"
                "对象，逐一列出并改写为「X、Y、Z 分别"
                "有什么用？」；若能判断用户最可能指最近"
                "或最突出的一个对象，则聚焦该对象改写。"
                "\n6. 改写后的问题必须包含可在知识库原文"
                "中直接匹配的具体名词，避免「文档」「内容」"
                "这类无法定位到具体段落的词。"
            ),
        },
        {
            "role": "user",
            "content": (
                f"对话历史：\n{history_text}\n\n"
                f"用户最新问题：{question}\n"
                "请输出改写后的完整问题。"
            ),
        },
    ]


def build_rerank_messages(
    question: str,
    candidates_text: str,
) -> list[dict[str, str]]:
    """
    构造 Rerank（重排序）使用的 Prompt。

    Rerank：
        Re = 重新
        Rank = 排序

    作用：
        根据用户问题，
        对已经检索出来的候选 Chunk
        重新判断相关性。

    要求模型返回 JSON，
    方便程序解析。
    """

    return [
        {
            "role": "system",
            "content": (
                "你是企业知识库 RAG 系统中的 Reranker（重排序器）。"

                "\n你的任务是判断候选文档片段"
                "与用户问题之间的真实相关程度。"

                "\n请重点判断："
                "\n1. 文档是否真正讨论用户问题。"
                "\n2. 文档是否包含能够回答问题的信息。"
                "\n3. 不要因为只出现相同关键词就给高分。"

                "\n\n评分范围：0 到 100。"

                "\n90-100：直接、完整回答问题。"
                "\n70-89：高度相关，包含主要答案依据。"
                "\n40-69：部分相关，但信息不完整。"
                "\n1-39：只有少量关联。"
                "\n0：完全无关。"

                "\n\n必须只返回 JSON 数组。"
                "\n不要输出 Markdown。"
                "\n不要输出解释性文字。"

                "\n格式："
                '\n['
                '{"index": 0, "score": 95, "reason": "理由"},'
                '{"index": 1, "score": 70, "reason": "理由"}'
                ']'
            ),
        },
        {
            "role": "user",
            "content": (
                f"用户问题：\n{question}"
                f"\n\n候选文档片段：\n{candidates_text}"
            ),
        },
    ]

def build_citation_rag_messages(
    question: str,
    context: str,
) -> list[dict[str, str]]:
    """
    构造 Citation RAG（带引用的 RAG）Prompt。

    citation
        = 引用、来源标注

    目标：
        让模型严格根据检索到的文档回答，
        并在相关事实后标注来源编号。

    示例：

        fastAI 是一个深度学习框架 [1]。
    """

    return [
        {
            "role": "system",
            "content": (
                "你是企业知识库问答助手。"

                "\n你只能根据系统提供的文档片段回答问题。"
                "\n不能使用文档片段之外的知识补充答案。"

                "\n\n引用规则："

                "\n1. 文档片段前会提供 [1]、[2] 等引用编号。"

                "\n2. 回答中的事实必须在对应内容后标注引用编号。"

                "\n3. 引用格式必须使用 [1]、[2]，"
                "不要自行创建不存在的编号。"

                "\n4. 如果一个事实由多个来源支持，"
                "可以写成 [1][2]。"

                "\n5. 如果文档片段与问题完全无关，"
                "请回答：文档中没有找到与该问题相关的信息。"
                "如果文档只包含部分相关信息（例如只提到"
                "术语的全称、定义或作用，却没有所问的"
                "实现细节），请先用引用编号说明文档中"
                "确实提到的内容，再明确指出文档未提供"
                "所问的具体部分，不要直接套用固定话术。"

                "\n6. 不允许为了完成回答而编造内容。"

                "\n最终回答使用清晰、简洁的中文。"
            ),
        },
        {
            "role": "user",
            "content": (
                f"文档片段：\n{context}"
                f"\n\n用户问题：\n{question}"
            ),
        },
    ]

